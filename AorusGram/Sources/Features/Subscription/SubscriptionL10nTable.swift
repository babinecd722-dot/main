// Languages the subscription UI speaks beyond Russian and English.
//
// Russian and English stay inline in SubscriptionL10n at each call site — that is how the
// file is written and it keeps the two primary languages readable next to each other.
// Every other language lives here, keyed by the English string, so adding a language is a
// single dictionary and touches nothing else. A key with no entry falls back to English,
// which is always safe to display.
//
// The keys must match the English literals in SubscriptionL10n exactly, including the
// typographic apostrophe (’). Strings that carry a value use a %@ placeholder rather than
// Swift interpolation: interpolating first would make the key differ on every render.
