// Languages AorusGram's own UI speaks beyond Russian and English.
//
// Russian and English stay inline in AorusL10n at each call site — that is how the file is
// written and it keeps the two primary languages readable side by side. Every other language
// lives here, keyed by the English string, so adding a language is a single dictionary and
// touches neither AorusL10n nor any call site. A key with no entry falls back to English,
// which is always safe to display.
//
// The keys must match the English literals in AorusL10n exactly — including the trailing
// space in "Deleted " and the %@ placeholders. Values are substituted after translation
// (see cacheIntervalValue/ramIntervalValue): interpolating first would make the key differ
// on every render, and the language would silently stay English.
